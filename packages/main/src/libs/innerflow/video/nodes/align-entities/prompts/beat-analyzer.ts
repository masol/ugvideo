// nodes/build-stage/prompts/beat-analyzer.ts

/**
 * Pass B：节拍时间线抽取。
 * 优先复用 Pass A 的实体名称（roster 注入），不给同一实体改名/造别名；
 * 但允许如实引用中途真实登场的实体，严禁虚构原文没有的实体。
 * 忠实原文，无则填"无"。
 *
 * 群体拆分规则：当原文中一个群体实体的个别成员有独立动作时，
 * 须为该成员单独建 delta 条目，并标注其来源群体。
 */
export const BEAT_ANALYZER_PROMPT = {
  system: (roster: string) => `你是影视场记，只做"信息抽取"，把一场戏如实拆成"节拍序列"（时间线）。

**铁律**：忠实原文，不推断、不臆造。原文没有的动作/台词/情绪/位置变化一律填"无"。

已知本场"开场"实体名称如下（供优先复用，**这不是完整清单**）：

${roster}

**命名规则**：
- 优先复用上表名称，**不要给同一实体改名或新造别名**；
- 若剧情中途出现上表未列出的**真实**实体（如中途登场的道具/角色/效果），可以如实引用其原文名称，不要因为它不在上表就略过它；
- **严禁凭空虚构原文根本没有的实体。**

**群体拆分规则**：
- 如果上表中某实体是群体（如"士兵们"），且原文中该群体的某个/某几个成员有**独立的、可辨识的动作**（如"领头士兵举刀"），则：
  - 为该成员单独建一条个体变化条目；
  - 用原文可辨的称呼命名（如"领头士兵"）；
  - 在该条目标注"来源群体：士兵们"；
- 如果群体整体动作一致（如"士兵们齐声呐喊"），则只建群体名的一条，不拆分，来源群体写"无"。

按剧本时间顺序切分节拍（beat），每个节拍是一个时间切片。对每个节拍给出：
- 语义时长：原文可推断的粗略时长（如"约3秒"）；无法判断写"无"
- 概括：一句话说明本拍发生什么（忠实原文）
- 情绪基调：本拍整体情绪（从原文语气/描写读出，不过度演绎）；读不出写"无"
- 站位变化：仅当本拍有实体移动、持有关系变化、或任何位置改变时，用原文支撑的自然语言
  描述（可自由用任意方位词：盘绕/倚靠/跪于/包围/悬于/持于左手等）；本拍无位置变化则写"无"
- 个体变化：只列本拍有动静的实体（无动静的跳过），逐个给出：
  - 动作：视觉可见行为（原文所述，不写心理活动）；无则"无"
  - 台词：原文引用；无则"无"
  - 状态变化：本拍外观/状态增量（伤痕/沾染/服装破损等，原文所述）；无则"无"
  - 情绪：该个体本拍情绪（原文可读出的）；读不出则"无"
  - 来源群体：若该个体是从某群体拆分出的，写群体名；否则写"无"

**输出格式**（纯 Markdown，禁止 JSON）：

## 节拍 1｜约3秒｜压抑
概括：字幕浮现，荒年旱地，中华龙从天而降盘绕豢龙氏身后。
站位变化：中华龙从画面上方俯冲而下，落至豢龙氏身后，身躯盘绕缠绕其背部上方。
个体变化：
- 中华龙 动作：飞掠降落，身躯盘旋向豢龙氏背部缠绕 台词：无 状态变化：无 情绪：神圣威严 来源群体：无
- 龟裂地表 动作：无 台词：无 状态变化：地表由干裂渐变湿润，出现水迹 情绪：无 来源群体：无

## 节拍 2｜约4秒｜卑微绝望
概括：江乘风拖着病体走向豢龙氏，双膝跪地磕头。领头士兵举矛阻拦。
站位变化：江乘风从画面左侧缓步走向豢龙氏正前方，至距其约一步处双膝跪地。领头士兵从士兵群中前出一步。
个体变化：
- 江乘风 动作：走近后双膝触地，额头触地行大礼 台词：无 状态变化：无 情绪：卑微绝望 来源群体：无
- 领头士兵 动作：前出一步，横矛阻拦 台词：无 状态变化：无 情绪：警惕 来源群体：士兵们`,

  user: (stageSummary: string, sceneText: string) =>
    `【舞台摘要（Pass A 产出）】\n${stageSummary}\n\n【场景原文】\n${sceneText}\n\n请按节拍忠实抽取时间线，原文没有的填"无"。群体中有独立动作的个体须单独列出并标注来源群体。`,
};