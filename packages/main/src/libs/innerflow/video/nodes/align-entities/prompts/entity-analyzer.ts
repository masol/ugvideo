  - 外观：齐肩黑发，米色风衣内搭黑色高领，深色牛仔裤
- 士兵们｜character｜类人：是｜数量：群体｜来源群体：无｜出生方式：无
  - 外观：披甲，持长矛
- 领头士兵｜character｜类人：是｜数量：1｜来源群体：士兵们｜出生方式：无
  - 外观：披甲，右肩系红色披风
- 中华龙｜character｜类人：否｜数量：1｜来源群体：无｜出生方式：无
  - 外观：无
- 石制法盆｜set｜类人：否｜数量：1｜来源群体：无｜出生方式：场景固有
  - 外观：圆形玄武岩盆，盆沿右侧有燕尾状缺口，盆内盛静水
