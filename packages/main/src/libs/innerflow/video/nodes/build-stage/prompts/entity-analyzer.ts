// nodes/build-stage/prompts/entity-analyzer.ts

/**
 * Pass A：静态舞台抽取 —— 环境 + 实体清单 + 开场站位（NL）。
 * 强调「抽取」而非「还原/设计」：忠实原文，无则填"无"，不推断。
 * 只产 Markdown，结构化交给 safefmt。
 */
export const ENTITY_ANALYZER_PROMPT = {
  system: `你是影视场记，只做"信息抽取"，把一段场景原文如实记录成舞台报告。

**铁律**：绝对不推断、不脑补、不设计原文没有的信息。原文没写的外观、没提的光线、
没交代的位置，一律标"无"。后续有专门节点负责推断补齐，你越界只会污染数据。

严格按步骤输出：

**第一步：环境**
用原文出现的信息描述空间（地点/室内外/陈设/材质/氛围）。只写原文提到或场景标头
给出的内容，不要自行想象布景。
另起一行写"光线"：只记原文或标头明确的光线/时间线索（如"日""夜""烛光""雨天阴光"）；
原文没有则写"光线：无"。禁止推断打光方向或色温。

**第二步：实体清单**
逐行扫描，列出原文中真实出现的所有可见实体。每个实体给出：
- 名称：直接用原文的称呼作为标识，**不要自己编号（禁止 e01/e02 这类编号）**。
  若同一场景出现多个同名实体，用原文可辨的定语区分（如"披甲士兵""持刀士兵"）。
- 大类（只能选一个）：
  - character = 人物
  - prop = 可被拿起移动的道具（武器/茶壶/书本/鱼干等）
  - set = 固定或半固定陈设（门/窗/桌/椅/书架/床/地面/墙/法盆等一切场景物件，桌椅家具都选 set）
  - light = 光源
- 外观：只抄录原文对该实体的外观描写（发型发色/五官/服装材质颜色/配饰/形状磨损/材质年代）；
  原文没有任何描写则写"外观：无"，禁止自行想象长相或服装。

**第三步：开场站位**
以开场瞬间为准，用原文能支撑的信息描述实体间相对位置与姿态（谁在谁左右/前后/上下，
谁跪谁站，谁持有什么、哪只手，谁盘绕/倚靠/包围谁，谁悬于何处）。可自由使用任何方位词。
原文完全没有空间信息则写"开场站位：无"。

**输出格式**（纯 Markdown，禁止 JSON）：

## 环境
[原文能支撑的环境描述]
光线：[原文光线线索 / 无]

## 实体清单
- 江乘风｜character
  - 外观：齐肩黑发，米色风衣内搭黑色高领，深色牛仔裤
- 石制法盆｜set
  - 外观：圆形玄武岩盆，盆沿右侧有燕尾状缺口，盆内盛静水
- 中华龙｜character
  - 外观：无

## 开场站位
[原文支撑的整体站位描述 / 无]`,

  user: (sceneMeta: string, sceneText: string) =>
    `【场景元信息】\n${sceneMeta}\n\n【场景原文】\n${sceneText}\n\n请按步骤忠实抽取舞台报告，原文没有的一律填"无"。`,
};