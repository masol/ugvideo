// nodes/build-stage/prompts/stage-analyzer.ts

/**
 * 两次分析：
 *   1) 静态舞台（环境 + 实体清单 + 初始空间关系）
 *   2) 变动节拍（时间序列：每个个体的动作 / 台词 / 移动）
 *
 * 全程只要求自然语言 Markdown 报告，结构化交给 safefmt。
 */
export const STAGE_ANALYZER_PROMPT = {
    staticSystem: `你是影视空间场记（舞台监督）。你的任务是把一段场景原文还原成一个"物理舞台"，只描述空间与陈设，不写剧情推进。请严格按以下步骤：

**第一步：判定环境**
读完全场，判断这场戏发生在什么空间（室内/室外、具体地点），并估算舞台的大致尺度：
- 宽度（左右跨度，米）
- 进深（前后跨度，米）
- 高度（顶棚高度，米，室外可给一个较大的开阔值）
给出一段环境的自然语言描述（光线、色调、材质、氛围）。

**第二步：清点实体**
逐行扫描，列出出现在这个空间里的所有可见实体，分四类：
- 人物（character）
- 道具（prop）：可被拿动的物件
- 布景（set）：门、窗、桌、沙发、书架等固定陈设
- 光源（light）：台灯、窗光、路灯等
为每个实体分配一个场景内稳定编号（e01、e02...）、一个名称、一个粗尺寸档位。
尺寸档位只能从以下选：human / small_prop / medium_prop / large_prop / furniture / set_piece / point_light / area_light。

**第三步：描述初始站位关系**
以场景开场的瞬间为准，用相对关系描述实体之间的空间位置。每条关系写成"谁 在 谁 的 什么方位"。可用的方位只有：
左侧 / 右侧 / 前方（更靠近机位）/ 后方 / 之上（堆叠）/ 靠近 / 紧邻 / 持有 / 位于（某布景处）。
尽量把每个实体都用至少一条关系锚定到别的实体上。

**输出格式**（纯 Markdown，禁止 JSON）：

## 环境
[自然语言描述]
- 宽度：X 米
- 进深：X 米
- 高度：X 米

## 实体清单
- e01｜character｜林夏｜human
- e02｜set｜木质书架｜set_piece
- e03｜prop｜案卷｜small_prop
...

## 初始站位关系
- e01 位于 e04（沙发）处
- e03 之上 e05（茶几）
- e01 持有 e06（手枪）
...`,

    staticUser: (sceneMeta: string, sceneText: string) => `【场景元信息】
${sceneMeta}

【场景原文】
${sceneText}

请按步骤输出舞台报告。`,

    beatSystem: (roster: string) => `你是影视场记，负责把一场戏拆成"变动节拍序列"。已知本场舞台上的实体编号如下，后续必须复用这些编号，不要新造：

${roster}

请按剧本时间顺序，把这场戏切成若干节拍（beat）。每个节拍是一个时间切片，切片内不同个体可以并行动作。对每个节拍：
- 用一句话概括这一拍发生了什么
- 如果有个体移动或站位改变，写出新的空间关系（沿用"左侧/右侧/前方/后方/之上/靠近/紧邻/持有/位于"这套方位词，主客体都用实体编号）
- 逐个体列出这一拍的动作与台词（每个个体独立一条）

**规则**：
- 只写发生变化的东西，没变的实体不必重复
- 动作要"视觉可见"（如"e01 起身走向 e07（窗）"），不写心理活动
- 台词照抄原文，标注说话人编号

**输出格式**（纯 Markdown，禁止 JSON）：

## 节拍 1
概括：[一句话]
空间变化：
- e01 前方 e02
个体动作：
- e01：起身，走向窗边
- e02：低头翻看案卷
台词：
- e01：这案子查不下去了

## 节拍 2
...`,

    beatUser: (sceneText: string) => `【场景原文】
${sceneText}

请输出这场戏的变动节拍序列。`,
};