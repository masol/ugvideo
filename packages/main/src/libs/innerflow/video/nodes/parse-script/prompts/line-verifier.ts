// parse-script/prompts/line-verifier.ts
import type { ScriptFormat } from "../types.js";

/**
 * 指令式：逐步验证，不是"判断是否为场景起始"的目标式。
 * format可为 null（格式识别失败时退化）。
 */
export function buildVerifierPrompt(
  candidateLineNo: number,
  markerText: string,
  contextNL: string,
  format: ScriptFormat | null
): string {
  const formatSection = format
    ? `已知剧本格式：
场景标记写法示例：${format.scene_marker_patterns.join("、") || "（未知）"}
集/幕标记写法示例：${format.episode_act_patterns.join("、") || "（无）"}
转场标记写法示例：${format.transition_patterns.join("、") || "（无）"}`
    : `（尚无已知格式，请仅凭文本自身判断）`;

  return `你正在验证剧本中的一行是否真的是"场景起始行"。

${formatSection}

待验证候选：
- 候选行号：${candidateLineNo}
- 候选行原文：${markerText}

以下是该行的上下文（前 5 行 + 后5 行，每行前有行号）：

${contextNL}

请按以下步骤执行：

**第一步：阅读候选行本身**
逐字读取候选行原文，判断它是否符合上述场景标记写法。把你的观察写出来。

**第二步：阅读上下文**
阅读候选行的前 3 行和后 3 行。
- 前面是否是另一个场景的结尾？
- 后面是否开始了场景动作描写或对白？

**第三步：做出判定**
基于以上两步，做出判定：
- 是场景起始行 → 给出置信度（0.0-1.0）
- 不是场景起始行 → 如果你认为真正的起始行在邻近（±5行以内），指出真正起始行号

**第四步：（仅当第三步判定为"是"时）抽取场景上下文**
从候选行及其后续几行中，尽量识别：
- 转场方式（硬切 / 叠化 / 淡入淡出 / 跳切 / 匹配剪辑 / 划像 / 其他 / 未识别）
- 粗略地点
- 粗略时间（白天/夜晚/黄昏 等）
- 出场人物名列表
- 挂载的集/幕标识（如 "第1集"；未识别则 "无"）
- 一句话概括本场景事件

---

输出格式：Markdown，严格按以下结构：

## 第一步观察

[你看到的候选行原文，是否符合已知格式]

## 第二步上下文

[前3行 / 后3行观察]

## 第三步判定

- 是否为场景起始：[是 / 否]
- 置信度：[0.0-1.0]
- 判定理由：[一句话]
- 若否且真起始行在邻近：真正起始行号 = [N]

## 第四步场景上下文（仅当判定为"是"时填写）

- 转场方式：[...]
- 粗略地点：[...]
- 粗略时间：[...]
- 出场人物：[角色1、角色2、...]
- 集/幕：[第x集 / 第x幕 / 无]
- 首行摘要：[一句话]`;
}