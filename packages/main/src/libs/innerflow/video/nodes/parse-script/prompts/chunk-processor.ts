// parse-script/prompts/chunk-processor.ts
import type { ScriptFormat } from "../types.js";

/**
 * 首次处理 chunk（无格式提示）
 *
 * 指令式：告诉 LLM 先做什么，再做什么；不是"找出所有场景"的目标式。
 */
export const FIRST_CHUNK_PROMPT = `你正在处理一份剧本的第一个片段。请严格按以下步骤顺序执行：

**第一步：识别格式**
从第一行开始逐行阅读，记录你观察到的格式规律：
- 场景是如何标记的？把你见到的行原文写出来作为例子（不要改写）
- 有没有集/幕划分？它们怎么标记的？写原文例子
- 有没有转场标记（如 CUT TO、划像、【切】等）？写原文例子
- 梗概/故事简介在哪里（剧本开头 / 有专门的 SYNOPSIS 段/ 没有）？
- 人物表在哪里（剧本开头 / 有专门的 CAST 段 / 散落在场景里 / 没有）？

用一段自然语言总结以上格式观察，注明原文样例。

**第二步：逐行扫描全局信息**
继续逐行阅读，找出"非场景内容"的全局段落（如标题页、梗概、人物表、序言、编者按等）。
对每一处，记录：
- 类型（title_page / synopsis / cast / preface / note / 其他）
- 行号区间（格式：[N1, N2]，1-based，含两端）
- 一句话内容摘要

如果没有全局段落，写"无全局信息"。

**第三步：逐行扫描场景起始**
逐行阅读，每当遇到符合第一步识别的"场景开始标记"时，记录：
- 该行的行号（与输入中的 <行号> 标记完全一致）
- 该行的原文（前60 字符）
- 对该场景的标题猜测（一句话）

注意：只标"场景起始行"本身，不要标场景内的任何行。不要漏掉短过渡场景。

**第四步：逐行扫描集/幕标记**
如果有集/幕划分，记录每一处集/幕标记的行号和原文片段。没有就写"无集幕标记"。

---

输出格式：Markdown，严格按以下结构（不要添加额外章节，不要 JSON）：

## 格式识别

[你的格式观察，含原文样例]

## 全局信息

- [类型] 行号区间 [N1, N2]，摘要：[内容]
（没有则写"无"）

## 场景起始行

- 行号 N｜原文：[前60字]｜标题猜测：[一句话]

## 集/幕标记

- 行号 N｜类型：[episode/act]｜原文：[片段]
（没有则写"无"）`;

/**
 * 后续 chunk（有格式提示）
 *
 * 指令式；格式描述只是推荐，LLM 见到冲突以自己为准。
 * 格式一致时只输出"格式一致"，不重复输出格式细节。
 */
export function buildSubsequentChunkPrompt(knownFormat: ScriptFormat): string {
    return `你正在处理一份剧本的后续片段。以下是之前 chunk 识别到的格式：

---
${knownFormat.description}

场景标记写法示例：${knownFormat.scene_marker_patterns.join("、") || "（未知）"}
集/幕标记写法示例：${knownFormat.episode_act_patterns.join("、") || "（无）"}
转场标记写法示例：${knownFormat.transition_patterns.join("、") || "（无）"}
梗概位置：${knownFormat.synopsis_location}
人物表位置：${knownFormat.cast_location}
---

请严格按以下步骤顺序执行：

**第一步：验证格式**
快速浏览本片段的前几行，判断上述格式描述是否与本片段一致。
- 如果一致：输出"格式一致，无需更新"，直接进行第二步
- 如果发现新的格式模式或与上述描述冲突：输出完整的更新后格式描述（覆盖上述全部字段，格式同"格式识别"章节）

**注意**：格式描述只是推荐。如果你在本片段中看到与上述不同的标记方式，以你观察到的实际情况为准。

**第二步：逐行扫描全局信息**
逐行阅读，找出非场景内容的全局段落（梗概、人物表、序言等）。
记录类型、行号区间 [N1, N2]、内容摘要（一句话）。没有则写"无"。

**第三步：逐行扫描场景起始**
逐行阅读，每当遇到场景开始标记时，记录行号（与输入中的 <行号> 标记完全一致）、原文前60 字符、标题猜测（一句话）。

**第四步：逐行扫描集/幕标记**
记录集/幕标记的行号和原文片段。没有则写"无"。

---

输出格式：Markdown，严格按以下结构：

## 格式更新

[若一致：] 格式一致，无需更新
[若不一致：] [完整更新后的格式描述，含原文样例]

## 全局信息

- [类型] 行号区间 [N1, N2]，摘要：[内容]
（没有则写"无"）

## 场景起始行

- 行号 N｜原文：[前60字]｜标题猜测：[一句话]

## 集/幕标记

- 行号 N｜类型：[episode/act]｜原文：[片段]
（没有则写"无"）`;
}