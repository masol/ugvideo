// ============================================================
// 组合导出：根据配置生成固化prompt 片段
// ============================================================

export interface StyleDirectiveConfig {
    pacing: string;
    style: string;
    color_tone: string;
    camera_movement: string;
    audience: string;
    aspect_ratio: string;
}

/**
 * 根据配置项组合生成固化的过程式 prompt 片段。
 * 每个配置值映射为固定文本，LLM 无需理解配置值含义。
 */
export function buildStyleDirectives(cfg: StyleDirectiveConfig): string {
    const blocks: string[] = [PACE_DIRECTIVES[cfg.pacing] ?? PACE_DIRECTIVES["normal"],
    STYLE_DIRECTIVES[cfg.style] ?? STYLE_DIRECTIVES["cinematic"],
    COLOR_TONE_DIRECTIVES[cfg.color_tone] ?? COLOR_TONE_DIRECTIVES["neutral"],
    CAMERA_DIRECTIVES[cfg.camera_movement] ?? CAMERA_DIRECTIVES["smooth"],
    AUDIENCE_DIRECTIVES[cfg.audience] ?? AUDIENCE_DIRECTIVES["pg"],
    ASPECT_RATIO_DIRECTIVES[cfg.aspect_ratio] ?? ASPECT_RATIO_DIRECTIVES["9:16"],
    ];
    return blocks.join("\n\n");
}